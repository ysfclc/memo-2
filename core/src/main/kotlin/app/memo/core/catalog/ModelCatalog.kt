/**
 * Role a model is suggested for. The orchestrator default is the smallest pinned
 * model; [DEEP] is the planner-size pick.
 */
enum class ModelRole { ORCHESTRATOR, CHAT, DEEP }

/**
 * One downloadable model file, pinned to an exact repository revision.
 *
 * [url] is always `https://huggingface.co/{repo}/resolve/{revision}/{file}`, and
 * [sha256] and [sizeBytes] come from the Hugging Face tree API (`lfs.oid`, `size`).
 * [family], [params], [quant] and [license] are descriptive; [quant] is null for
 * LiteRT-LM files, which carry no quantisation label in their name.
 * [minRamBytes] is an estimate (file size + 25% + 512 MiB), not a measurement;
 * 0 means no memory preflight beyond storage.
 */
data class ModelEntry(
    val id: String,
    val displayName: String,
    val role: ModelRole,
    val format: ModelFormat,
    val repo: String,
    val revision: String,
    val file: String,
    val url: String,
    val sha256: String,
    val sizeBytes: Long,
    val family: String,
    val params: String?,
    val quant: String?,
    val license: String?,
    val gated: Boolean,
    val minRamBytes: Long,
    val thinkingByDefault: Boolean,
    val outputTokenBudget: Int,
    val description: String,
) {
    init {
        require(ID_PATTERN.matches(id)) { "invalid model id: $id" }
        require(REVISION_PATTERN.matches(revision)) { "revision must be a 40-hex commit sha: $revision" }
        require(ModelCatalog.isSha256Shape(sha256)) { "sha256 must be 64 lowercase hex characters" }
        require(sizeBytes > 0) { "sizeBytes must be > 0" }
        require(url == HfParsers.pinnedUrl(repo, revision, file)) { "url must be the pinned resolve URL" }
        require(file.endsWith(if (format == ModelFormat.GGUF) ".gguf" else ".litertlm")) {
            "file extension does not match format $format"
        }
        require(minRamBytes >= 0 && outputTokenBudget >= 0) { "budgets must be >= 0" }
    }

    val isRunnableSize: Boolean
        get() = sizeBytes >= Limits.MIN_MODEL_BYTES || sizeBytes == 0L

    private companion object {
        val ID_PATTERN = Regex("^[a-z0-9][a-z0-9.-]{0,63}$")
        val REVISION_PATTERN = Regex("^[0-9a-f]{40}$")
    }
}

